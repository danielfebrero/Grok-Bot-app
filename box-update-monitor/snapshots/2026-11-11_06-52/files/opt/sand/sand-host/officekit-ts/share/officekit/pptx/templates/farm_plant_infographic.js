// Shared options for sh()/art(): rot, fh/fv (flips), ln:{c,w,dash},
// r (corner radius) and sd = [blur, offset, angle, opacity] soft shadow.
function common(opt, o) {
  if (o.rot) opt.rotate = o.rot;
  if (o.fh) opt.flipH = true;
  if (o.fv) opt.flipV = true;
  if (o.ln) opt.line = { color: o.ln.c, width: o.ln.w, dashType: o.ln.dash ? 'dash' : 'solid' };
  if (o.r !== undefined) opt.rectRadius = o.r;
  if (o.sd) opt.shadow = { type: 'outer', color: BLACK, blur: o.sd[0], offset: o.sd[1], angle: o.sd[2], opacity: o.sd[3] };
  return opt;
}

/** Preset-geometry shape (rect, ellipse, roundRect, triangle, line, ...). */
function sh(s, prst, x, y, w, h, fill, o) {
  const opt = common({ x, y, w, h }, o || {});
  if (fill) opt.fill = { color: fill };
  s.addShape(prst, opt);
}

/**
 * Freeform shape built from an entry of the outline library A.
 *
 * An outline is an SVG-ish path string of space separated commands:
 *   Mx,y                move to
 *   Lx,y                line to
 *   Cx1,y1,x2,y2,x,y    cubic bezier
 *   Z                   close sub-path
 * Coordinates run 0..1000 across the shape's own box (pptxgenjs wants path
 * points relative to the shape), so one outline is reusable at any size.
 */
function art(s, cmds, x, y, w, h, fill, o) {
  const pts = [];
  for (const cmd of cmds.split(' ')) {
    const kind = cmd[0];
    if (kind === 'Z') { pts.push({ close: true }); continue; }
    const n = cmd.slice(1).split(',').map(Number);
    const P = [];
    for (let i = 0; i < n.length; i += 2) P.push([(n[i] / 1000) * w, (n[i + 1] / 1000) * h]);
    if (kind === 'M') pts.push({ x: P[0][0], y: P[0][1], moveTo: true });
    else if (kind === 'L') pts.push({ x: P[0][0], y: P[0][1] });
    else if (kind === 'C') pts.push({ x: P[2][0], y: P[2][1], curve: { type: 'cubic', x1: P[0][0], y1: P[0][1], x2: P[1][0], y2: P[1][1] } });
    else if (kind === 'Q') pts.push({ x: P[1][0], y: P[1][1], curve: { type: 'quadratic', x1: P[0][0], y1: P[0][1] } });
  }
  const opt = common({ x, y, w, h, points: pts }, o || {});
  if (fill) opt.fill = { color: fill };
  s.addShape('custGeom', opt);
}

/**
 * Text box.  o: mj = use the major (heading) font, b/i = bold/italic,
 * sp = character spacing in points, al = l|c|r, ls = line-spacing multiple.
 */
function tx(s, x, y, w, h, text, size, color, o) {
  o = o || {};
  s.addText(text, {
    x, y, w, h, fontSize: size, color,
    fontFace: o.mj ? HEAD_FONT : BODY_FONT,
    bold: !!o.b, italic: !!o.i, charSpacing: o.sp,
    align: { c: 'center', r: 'right' }[o.al] || 'left',
    lineSpacingMultiple: o.ls,
    valign: 'top', wrap: true, isTextBox: true,
  });
}

