/** Draw one slide's simplified illustration from the ART table. */
function illustration(s, n) {
  const shapes = ART[n];
  if (!shapes) return;
  shapes.forEach(function (sh) {
    const fill = { color: sh[0] };
    const x = sh[1], y = sh[2], w = sh[3], h = sh[4];
    for (let i = 5; i < sh.length; i++) {
      const g = sh[i];
      if (typeof g === 'string') { s.addShape(g, { x, y, w, h, fill }); continue; }
      const pts = [];  // polygon coords are relative to the shape's own box
      for (let k = 0; k < g.length; k += 2) {
        pts.push({ x: (g[k] / 100) * w, y: (g[k + 1] / 100) * h });
      }
      pts.push({ close: true });
      s.addShape('custGeom', { x, y, w, h, fill, line: { type: 'none' }, points: pts });
    }
  });
}

