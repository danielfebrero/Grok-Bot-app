/** One free-form contour, coordinates given as fractions of `w` x `h`. */
function contour(s, x, y, w, h, coords, color) {
  const pts = [];   // custGeom points are relative to the shape's own box
  for (let i = 0; i < coords.length; i += 2) pts.push({ x: coords[i] * w, y: coords[i + 1] * h });
  pts.push({ close: true });
  s.addShape('custGeom', { x, y, w, h, points: pts, fill: { color }, line: { type: 'none' } });
}

/** White line icon drawn inside its bounding box; holes punch back to `back`. */
function icon(s, name, x, y, w, h, back) {
  ICONS[name].forEach(function (c) {
    contour(s, x, y, w, h, c.slice(1), c[0] === 'f' ? C.white : (back || C.bg));
  });
}

