/** Headline set in Montserrat, white, top-aligned. */
function headline(s, x, y, w, h, text, size, opts) {
  opts = opts || {};
  s.addText(text, {
    x, y, w, h, fontFace: FONT_H, fontSize: size, color: C.white,
    align: opts.align || 'left', valign: 'top', fit: 'none',
    lineSpacingMultiple: opts.lineSpacing === undefined ? 0.9 : opts.lineSpacing,
  });
}

/** 12 pt Rubik body copy, white, top-aligned; the deck leads these at 120%. */
function body(s, x, y, w, h, text, opts) {
  opts = opts || {};
  s.addText(text, {
    x, y, w, h, fontFace: FONT_B, fontSize: opts.size || 12, color: opts.color || C.white,
    align: opts.align || 'left', valign: 'top', fit: 'none',
    lineSpacingMultiple: opts.lineSpacing === undefined ? 1.2 : opts.lineSpacing,
    paraSpaceAfter: 6,
  });
}

/** Teal bullet marker: solid disc when `filled`, otherwise a 3 pt ring. */
function marker(s, x, y, d, filled) {
  s.addShape('ellipse', filled
    ? { x, y, w: d, h: d, fill: { color: C.teal }, line: { type: 'none' } }
    : { x, y, w: d, h: d, fill: { type: 'none' }, line: { color: C.teal, width: 3 } });
}

/** Row of `n` markers, only the first one solid (the deck's page indicator). */
function markerRow(s, x, y, d, gap, n) {
  for (let i = 0; i < n; i++) marker(s, x + i * gap, y, d, i === 0);
}

/** Marker + paragraph, the deck's standard annotation pairing. */
function note(s, mx, my, md, filled, tx, ty, tw, th, text, opts) {
  marker(s, mx, my, md, filled);
  body(s, tx, ty, tw, th, text, opts);
}

