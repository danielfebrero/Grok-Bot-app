/*
 * Outlines are stored as compact SVG-style path data in a 0..1 unit box, so a
 * shape can be dropped anywhere at any size.  Supported commands: M/L/C/Z.
 */
function parsePath(d) {
  const pts = [];
  const tokens = d.split(' ');
  for (let i = 0; i < tokens.length; ) {
    const cmd = tokens[i][0];
    const num = (t) => parseFloat(t);
    if (cmd === 'Z') { pts.push({ close: true }); i += 1; continue; }
    const head = tokens[i].slice(1);
    if (cmd === 'M') {
      pts.push({ x: num(head), y: num(tokens[i + 1]), moveTo: true });
      i += 2;
    } else if (cmd === 'L') {
      pts.push({ x: num(head), y: num(tokens[i + 1]) });
      i += 2;
    } else if (cmd === 'C') {
      pts.push({
        x: num(tokens[i + 4]), y: num(tokens[i + 5]),
        curve: {
          type: 'cubic',
          x1: num(head), y1: num(tokens[i + 1]),
          x2: num(tokens[i + 2]), y2: num(tokens[i + 3]),
        },
      });
      i += 6;
    } else {
      throw new Error('bad path command: ' + tokens[i]);
    }
  }
  return pts;
}

/* Scale unit-box path points to the shape's own w x h coordinate space. */
function place(pts, w, h) {
  return pts.map((p) => {
    if (p.close) return p;
    const q = { x: p.x * w, y: p.y * h };
    if (p.moveTo) q.moveTo = true;
    if (p.curve) {
      q.curve = {
        type: 'cubic',
        x1: p.curve.x1 * w, y1: p.curve.y1 * h,
        x2: p.curve.x2 * w, y2: p.curve.y2 * h,
      };
    }
    return q;
  });
}

// ---------------------------------------------------------------- drawing api
let S = null; // slide currently being built

function poly(d, x, y, w, h, fill, opts) {
  S.addShape('custGeom', Object.assign(
    { x, y, w, h, points: place(parsePath(d), w, h), line: { type: 'none' } },
    fill ? { fill } : {}, opts || {}));
}

function box(shape, x, y, w, h, fill, opts) {
  S.addShape(shape, Object.assign(
    { x, y, w, h, line: { type: 'none' } },
    fill ? { fill } : {}, opts || {}));
}

function txt(text, x, y, w, h, opts) {
  S.addText(text, Object.assign(
    { x, y, w, h, fontFace: FONT, fontSize: 10, color: C.white, margin: 0,
      valign: 'top', wrap: true }, opts || {}));
}

/* A vertically centred number/year badge (the deck's 01..10 and 2023..2028 chips). */
function label(text, x, y, w, h, fontSize, bold) {
  txt(text, x, y, w, h,
    { fontSize, bold: bold !== false, align: 'center', valign: 'middle' });
}

/* Pictogram: a coloured outline drawn inside the given box. */
function icon(name, x, y, w, h, color) {
  poly(ICONS[name], x, y, w, h, color);
}

