// Array of strings -> one paragraph per string. pptxgenjs does not inherit
// `bullet` from the shape options, so it is repeated on every paragraph.
function lines(text, bullet) {
  const arr = Array.isArray(text) ? text : [text];
  return arr.map((t, i) => ({
    text: t,
    options: { breakLine: i < arr.length - 1, bullet: bullet || undefined },
  }));
}

// Path library entries are unit-square segments, relative to the shape box:
//   [x, y]                         move-to / line-to
//   [x1, y1, x2, y2, x, y]         cubic bezier
//   []                             close path
// `toPoints` scales them to the shape's width/height (pptxgenjs wants inches
// measured from the shape's own top-left corner).
function toPoints(segs, box) {
  const px = (v) => v * box.w;
  const py = (v) => v * box.h;
  return segs.map((seg, i) => {
    if (seg.length === 0) return { close: true };
    if (seg.length === 6) {
      return { x: px(seg[4]), y: py(seg[5]),
        curve: { type: 'cubic', x1: px(seg[0]), y1: py(seg[1]), x2: px(seg[2]), y2: py(seg[3]) } };
    }
    return { x: px(seg[0]), y: py(seg[1]), moveTo: i === 0 || segs[i - 1].length === 0 };
  });
}

