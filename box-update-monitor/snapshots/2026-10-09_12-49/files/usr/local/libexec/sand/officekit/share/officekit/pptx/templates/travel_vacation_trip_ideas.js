/** Text box with the deck's shared defaults (top anchored, Poppins, tight insets). */
function T (s, text, o) {
  s.addText(text, Object.assign({ fontFace: REG, color: INK, valign: 'top', margin: PAD, isTextBox: true }, o));
}

/** Freeform shape from sub-paths given in per-mille of the shape's own box. */
function poly (s, x, y, w, h, subpaths, o) {
  const points = [];
  subpaths.forEach(sp => {
    for (let i = 0; i < sp.length; i += 2) {
      points.push({ x: (sp[i] / 1000) * w, y: (sp[i + 1] / 1000) * h, moveTo: i === 0 });
    }
    points.push({ close: true });
  });
  s.addShape(S.custGeom, Object.assign({ x, y, w, h, points }, o));
}

