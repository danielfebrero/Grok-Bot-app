/** Rotate (px,py) clockwise about (cx,cy) by 0/90/180/270 degrees. */
function spin(px, py, cx, cy, deg) {
  const dx = px - cx, dy = py - cy;
  if (deg === 90) return [cx - dy, cy + dx];
  if (deg === 180) return [cx - dx, cy - dy];
  if (deg === 270) return [cx + dy, cy - dx];
  return [px, py];
}

/**
 * Staircase triangle of 25 squircles (9 wide, 5 deep) — the corner motif.
 * Untranslated it is 3.39 x 1.705in and points downwards; `rot` turns it.
 */
const STAIR_ROWS = [0, 0.376, 0.725, 1.078, 1.441];
function stairField(slide, x, y, w, color, rot) {
  const k = w / 3.39, cell = 0.264 * k, gx = 0.3915 * k;
  const cx = x + w / 2, cy = y + 1.705 * k / 2;
  STAIR_ROWS.forEach((rowY, r) => {
    for (let c = r; c <= 8 - r; c++) {
      const [px, py] = spin(x + c * gx + cell / 2, y + rowY * k + cell / 2, cx, cy, rot || 0);
      diamond(slide, px - cell / 2, py - cell / 2, cell, color);
    }
  });
}

/** Dense grid of small circles: `cols` x `rows` filling the given box. */
function dotField(slide, x, y, w, h, cols, rows, color, rot) {
  const d = 0.07 * (w / 2.168);
  const gx = (w - d) / (cols - 1), gy = (h - d) / (rows - 1);
  const cx = x + w / 2, cy = y + h / 2;
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const [px, py] = spin(x + c * gx + d / 2, y + r * gy + d / 2, cx, cy, rot || 0);
      oval(slide, px - d / 2, py - d / 2, d, d, color);
    }
  }
}

/** The standard 12x5 dot block — 2.168 x 0.579in unless overridden. */
const dotBlock = (slide, x, y, color, rot, w, h) =>
  dotField(slide, x, y, w || 2.168, h || 0.579, 12, 5, color, rot);

