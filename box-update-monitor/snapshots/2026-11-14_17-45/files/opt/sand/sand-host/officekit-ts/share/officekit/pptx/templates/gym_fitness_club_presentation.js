// ------------------------------------------------------------------ helpers
// Deck defaults: Roboto 12pt white, top-aligned, PowerPoint's standard insets.
function text(s, body, opts) {
  s.addText(body, Object.assign(
    { margin: INSET, valign: 'top', fontFace: BODY_FONT, fontSize: 12, color: WHITE }, opts));
}

// One-line bold label (names, headings inside cards, percentages).
function label(s, x, y, w, h, copy, o) {
  o = o || {};
  text(s, copy, Object.assign({ x, y, w, h, bold: true }, o));
}

// "Your Name Here" over "Your Job Descriptions", centred under a portrait.
function person(s, x, y, w, name, job) {
  label(s, x, y, w, 0.303, name, { align: 'center' });
  text(s, job, { x, y: y + 0.303, w, h: 0.303, align: 'center', color: GREY65 });
}

function shape(s, kind, opts) {
  s.addShape(kind, opts);
}

// Freeform outlines are lists of closed sub-paths whose points are given as
// percentages of the shape's own bounding box; `poly` scales them onto the slide.
function poly(s, subPaths, opts) {
  const { w, h } = opts;             // path points are box-relative percentages
  const points = [];
  subPaths.forEach(sub => {
    sub.forEach((p, i) => points.push({ x: p[0] * w / 100, y: p[1] * h / 100, moveTo: i === 0 }));
    points.push({ close: true });
  });
  s.addShape('custGeom', Object.assign({ line: { type: 'none' } }, opts, { points }));
}

// Photo frames. The source template ships these as *empty* picture
// placeholders - nothing is painted, the dark background shows through - so
// the stand-in is a fully transparent rectangle of the same geometry. Flip
// SHOW_PHOTO_FRAMES to true to see where artwork would be dropped in.
const SHOW_PHOTO_FRAMES = false;
function imageFrame(s, x, y, w, h) {
  if (!SHOW_PHOTO_FRAMES) {
    shape(s, 'rect', { x, y, w, h, fill: { color: BG, transparency: 100 } });
    return;
  }
  shape(s, 'rect', { x, y, w, h, fill: '2B2B2B', line: { color: '3D3D3D', width: 1 } });
  text(s, '[image]', { x, y, w, h, align: 'center', valign: 'middle',
                       fontFace: BODY_FONT, fontSize: 12, color: '8A8A8A' });
}

// Eyebrow + big title, the header used on almost every content slide.
function heading(s, x, y, w, title, o) {
  o = o || {};
  text(s, BRAND, { x, y, w, h: 0.438, fontFace: KICK_FONT, fontSize: 20,
                   color: RED, align: o.align });
  text(s, title, { x, y: y + 0.438, w: o.titleW || w, h: 0.572, fontFace: HEAD_FONT,
                   fontSize: 28, bold: true, charSpacing: 1, color: WHITE, align: o.align });
}

// A plain 12pt paragraph: grey, 1.5 line spacing, justified unless told otherwise.
function body(s, x, y, w, h, copy, o) {
  o = o || {};
  text(s, copy, { x, y, w, h, fontFace: BODY_FONT, fontSize: 12,
                  color: o.color || GREY65, align: o.align || 'justify',
                  lineSpacingMultiple: 1.5 });
}

// Bold 12pt lead-in with a justified paragraph directly beneath it.
function captioned(s, x, y, w, h, caption, body, o) {
  o = o || {};
  const align = o.align || 'justify';
  const capAlign = align === 'center' || align === 'right' ? align : 'left';
  text(s, caption, { x, y, w: o.subW || w, h: 0.303, fontFace: BODY_FONT, fontSize: 12,
                     bold: true, color: WHITE, align: capAlign });
  text(s, body, { x, y: y + 0.303, w, h, fontFace: BODY_FONT, fontSize: 12,
                  color: o.color || GREY65, align, lineSpacingMultiple: 1.5 });
}

// Red numbered disc followed by a caption + paragraph, offset 0.843" to its right.
function numberedStep(s, x, y, label, w, caption, body) {
  text(s, label, { x, y, w: 0.61, h: 0.61, shape: 'ellipse', fill: { color: RED },
                   align: 'center', valign: 'middle',
                   fontFace: BODY_FONT, fontSize: 24, bold: true, color: WHITE });
  captioned(s, x + 0.843, y, w, 0.673, caption, body);
}

// Skill meter: grey track, red fill, title on the left, percentage on the right.
function progressBar(s, x, y, w, title, pct, filled) {
  label(s, x - 0.096, y - 0.408, 2.273, 0.303, title);
  label(s, x + 3.167, y - 0.408, 2.273, 0.303, pct, { align: 'right' });
  shape(s, 'line', { x, y, w, h: 0, line: { color: GREY75, width: 5 } });
  shape(s, 'line', { x, y, w: filled, h: 0, line: { color: RED, width: 5 } });
}

