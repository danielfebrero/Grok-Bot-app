// Slide 1 has a vertical alpha gradient; approximate it with stacked bands.
function gradientBands(slide, top, bottom, bands) {
  const mix = (a, b, t) =>
    [0, 2, 4].map((i) => Math.round(parseInt(a.substr(i, 2), 16) * (1 - t) + parseInt(b.substr(i, 2), 16) * t))
      .map((v) => ('0' + v.toString(16)).slice(-2).toUpperCase()).join('');
  for (let i = 0; i < bands; i++) {
    slide.addShape('rect', {
      x: 0, y: (7.5 / bands) * i, w: 13.334, h: 7.5 / bands + 0.06,
      fill: { color: mix(top, bottom, i / (bands - 1)) }, line: { type: 'none' },
    });
  }
}

// Draw traced vector artwork: each entry is a shape whose `p` holds one or
// more closed sub-paths of flat [x0,y0,x1,y1,...] inch coordinates.
function paintArt(slide, art) {
  art.forEach(function (a) {
    const points = [];
    a.p.forEach(function (sub) {
      for (let i = 0; i < sub.length; i += 2) points.push({ x: sub[i], y: sub[i + 1], moveTo: i === 0 });
      points.push({ close: true });
    });
    slide.addShape('custGeom', {
      x: a.x, y: a.y, w: a.w, h: a.h, rotate: a.rot || 0, points: points,
      fill: a.fill ? { color: a.fill, transparency: a.transp || 0 } : { type: 'none' },
      line: a.line ? { color: a.line, width: a.lw } : { type: 'none' },
    });
  });
}

