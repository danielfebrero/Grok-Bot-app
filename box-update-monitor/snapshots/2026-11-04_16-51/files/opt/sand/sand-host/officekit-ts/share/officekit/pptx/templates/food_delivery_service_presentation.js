// Ring (donut) drawn as an outer + inner circular sub-path.
function circlePath(cx, cy, r) {
  const k = 0.5523 * r;
  return [[cx, cy - r], [cx + k, cy - r, cx + r, cy - k, cx + r, cy], [cx + r, cy + k, cx + k, cy + r, cx, cy + r],
          [cx - k, cy + r, cx - r, cy + k, cx - r, cy], [cx - r, cy - k, cx - k, cy - r, cx, cy - r], 'z'];
}
function ring(s, x, y, d, thick, color) {
  const r = d / 2;
  const cmds = circlePath(0.5, 0.5, 0.5).concat(['m'], circlePath(0.5, 0.5, (r - thick) / d));
  poly(s, x, y, d, d, cmds, { fill: { color } });
}

