// One wallpaper cell = arch + notched bar + bun, tiled on a 2.55 x 2.62 grid.
const TILE = [
  [0, 0, 2.035, 0.78, [[.5, 0], [.776, 0, 1, .283, 1, 1], [0, 1], [0, .276, .224, 0, .5, 0], 'z']],
  [.01, .98, 2.035, 0.6, [[.088, 0], [.912, 0], [.96, 0, 1, .137, 1, .299], [1, .462, .96, .598, .912, .598],
    [.749, .598], [.621, 1], [.495, .598], [.088, .598], [.04, .598, 0, .462, 0, .299], [0, .137, .04, 0, .088, 0], 'z']],
  [0, 1.53, 2.04, 0.48, [[0, 0], [.446, 0], [.619, .681], [.794, 0], [1, 0], [1, .5],
    [1, .777, .947, 1, .882, 1], [.118, 1], [.053, 1, 0, .777, 0, .5], 'z']],
];
function wallpaper(s, ox, oy, cols, rows, color, scale) {
  const k = scale || 1;
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      for (const [dx, dy, w, h, cmds] of TILE) {
        poly(s, ox + (c * 2.55 + dx) * k, oy + (r * 2.62 + dy) * k, w * k, h * k, cmds, { fill: { color } });
      }
    }
  }
}
// Paints `color` over the whole slide except inside `cmds`, so a wallpaper
// drawn underneath ends up clipped to that outline (even-odd fill rule).
const RECT_PATH = [[0, 0], [1, 0], [1, 1], [0, 1], 'z'];
function maskOutside(s, cmds, x, y, w, h, color) {
  const inner = cmds.map(c => (typeof c === 'string' ? c : c.map((v, i) => (i % 2 ? (y + v * h) / 7.5 : (x + v * w) / 13.333))));
  poly(s, 0, 0, 13.333, 7.5, RECT_PATH.concat(['m'], inner), { fill: { color: color } });
}
// Wallpaper laid on a 2.55 x 2.62 grid anchored at (ox, oy), clipped to a shape.
function clipWallpaper(s, ox, oy, scale, color, outline, x, y, w, h) {
  const k = scale || 1;
  wallpaper(s, ox, oy, Math.ceil((x + w - ox) / (2.55 * k)), Math.ceil((y + h - oy) / (2.62 * k)), color, k);
  maskOutside(s, outline || RECT_PATH, x, y, w, h, C.white);
}
// Pill outline (roundRect adj=50000) normalised to a w x h box.
function stadiumPath(w, h) {
  const r = Math.min(w, h) / 2 / w, K = 0.5523;
  return [[r, 0], [1 - r, 0], [1 - r + K * r, 0, 1, 0.5 - K * 0.5, 1, 0.5],
          [1, 0.5 + K * 0.5, 1 - r + K * r, 1, 1 - r, 1], [r, 1],
          [r - K * r, 1, 0, 0.5 + K * 0.5, 0, 0.5], [0, 0.5 - K * 0.5, r - K * r, 0, r, 0], 'z'];
}

