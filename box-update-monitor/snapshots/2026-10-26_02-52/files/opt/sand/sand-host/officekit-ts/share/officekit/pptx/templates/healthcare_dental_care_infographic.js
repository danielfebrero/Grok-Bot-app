/* ---------------------------------------------------------------- helpers --
 * Every helper takes the slide first, then x, y, w, h in inches, then an
 * options bag with short keys:  t = fill transparency %, ln/lw/lt = line
 * colour / width / transparency, rot = rotation, fh = flip horizontally,
 * sh = drop shadow, al = align (l|c|r), va = vertical align (t|m|b),
 * c = colour, sz = font size, b = bold, ls = line-spacing multiple.
 */
function fillOf(color, o) {
  if (!color) return { type: 'none' };
  return o && o.t ? { color: color, transparency: o.t } : { color: color };
}
function lineOf(o) {
  if (!o || !o.ln) return undefined;
  const l = { color: o.ln };
  if (o.lw) l.width = o.lw;
  if (o.lt) l.transparency = o.lt;
  if (o.arrow) l.endArrowType = 'triangle';
  return l;
}
function common(x, y, w, h, o) {
  o = o || {};
  const p = { x: x, y: y, w: w, h: h };
  const l = lineOf(o);
  if (l) p.line = l;
  if (o.rot) p.rotate = o.rot;
  if (o.fh) p.flipH = true;
  if (o.sh) p.shadow = SH;
  return p;
}
