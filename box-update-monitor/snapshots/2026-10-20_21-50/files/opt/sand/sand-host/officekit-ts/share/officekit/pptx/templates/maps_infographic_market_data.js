// Text box. Geometry is positional; everything else has deck-wide defaults.
function tx(s, text, x, y, w, h, o) {
  o = o || {};
  s.addText(text, {
    x: x, y: y, w: w, h: h,
    fontFace: o.font || BODY,
    fontSize: o.size || 18,
    color: o.color || INK,
    align: o.align || 'left',
    valign: o.valign || 'top',
    lineSpacingMultiple: o.lh || 1,
    paraSpaceAfter: o.after,
    bullet: o.bullet ? { characterCode: '2022', indent: 13.5 } : false,
    margin: [7.2, 7.2, 3.6, 3.6],
    wrap: true,
  });
}

// Auto-shape. `lw: 0` means no outline; `rad` is the rounded-corner radius.
function sh(s, kind, x, y, w, h, o) {
  o = o || {};
  const opt = { x: x, y: y, w: w, h: h };
  if (o.fill) opt.fill = o.alpha ? { color: o.fill, transparency: o.alpha } : { color: o.fill };
  opt.line = o.lw === 0 ? { type: 'none' }
    : { color: o.lc || INK, width: o.lw || 0.5, dashType: o.dash, endArrowType: o.arrow };
  if (o.rad != null) opt.rectRadius = o.rad;
  if (o.arc) opt.angleRange = o.arc;
  if (o.rot) opt.rotate = o.rot;
  if (o.flipV) opt.flipV = true;
  if (o.shadow) opt.shadow = SHADOW;
  if (o.text) {
    opt.shape = kind;
    opt.fontFace = o.font || BODY;
    opt.fontSize = o.size || 14;
    opt.color = o.color || WHITE;
    opt.align = 'center';
    opt.valign = 'middle';
    opt.margin = [7.2, 7.2, 3.6, 3.6];
    s.addText(o.text, opt);
  } else {
    s.addShape(kind, opt);
  }
}

// Straight rule / connector.
function rule(s, x, y, w, h, o) {
  o = o || {};
  s.addShape('line', {
    x: x, y: y, w: w, h: h,
    line: { color: o.color || INK, width: o.width || 1, dashType: o.dash, endArrowType: o.arrow },
  });
}

// "----- Maps Infographic" eyebrow. `rules` is the list of rule x-offsets.
function eyebrow(s, x, y, rules) {
  tx(s, 'Maps Infographic', x, y, 1.8, 0.34, { size: 14, font: HEAD });
  (rules || [x - 1.01]).forEach(function (rx) { rule(s, rx, y + 0.17, 0.95, 0); });
}

// Pill button ("Learn More" / "Get Started").
function button(s, x, y, label, fill) {
  sh(s, 'roundRect', x, y, 1.365, 0.429, { fill: fill || ORANGE, rad: 0.215 });
  tx(s, label, x + 0.05, y + 0.047, 1.265, 0.337, { size: 14, font: HEAD, color: WHITE, align: 'center' });
}

// Rounded square step badge ("01." / "02.").
