// Map pin: teardrop + white eye.
function pin(s, x, y, w, fill) {
  const h = w * 1.4538, d = w * 0.6239;
  s.addShape('custGeom', {
    x: x, y: y, w: w, h: h, fill: { color: fill }, line: { color: INK, width: 0.5 },
    points: PIN_OUTLINE.map(function (p) { return { x: p[0] * w, y: p[1] * h }; }).concat([{ close: true }]),
  });
  sh(s, 'ellipse', x + w * 0.188, y + w * 0.188, d, d, { fill: WHITE, lc: BLACK, lw: 0.75 });
}
const PIN_OUTLINE = [[.5,0],[.24,.05],[.07,.17],[0,.34],[.07,.52],[.5,1],[.93,.52],[1,.34],[.93,.17],[.76,.05]];

// Pictogram person (head + shoulders) used on the population counters.
function person(s, x, y, w, fill, fade, flat) {
  const head = w * 0.6, bw = w, bh = w * 2.137;
  const edge = flat ? { type: 'none' } : { color: INK, width: 0.5 };
  sh(s, 'ellipse', x + (w - head) / 2, y, head, head, { fill: fill, alpha: fade, lw: flat ? 0 : 0.5 });
  s.addShape('custGeom', {
    x: x, y: y + w * 0.797, w: bw, h: bh,
    fill: { color: fill, transparency: fade }, line: edge,
    points: PERSON_BODY.map(function (p) { return { x: p[0] * bw, y: p[1] * bh }; }).concat([{ close: true }]),
  });
}
