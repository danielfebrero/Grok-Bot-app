// Ring gauge: pale disc + heavy arc sweep. `sweep` is the open-end angle.
function gauge(s, x, y, d, disc, sweep, o) {
  o = o || {};
  if (disc) sh(s, 'ellipse', x, y, d, d, { fill: disc });
  const i = d * 0.0982, id = d * 0.8036;
  sh(s, 'arc', x + i, y + i, id, id, { arc: [272.87, sweep], lc: o.arcColor || INK, lw: o.arcWidth || 3.75 });
}

// Evenly spaced run of person pictograms (population counters).
function personRow(s, x, y, box, step, count, fill, fadeFrom) {
  const w = box / 2.934;                       // person() is 2.934 x its own width
  for (let i = 0; i < count; i++) {
    person(s, x + i * step + (box - w) / 2, y, w, fill, i >= (fadeFrom || count) ? 55 : 0, true);
  }
}

// Flat stand-in for a photo in the original deck.
function imageBox(s, x, y, w, h) {
  sh(s, 'rect', x, y, w, h, { fill: GREY, lw: 0 });
  tx(s, '[image]', x, y + h / 2 - 0.2, w, 0.4, { size: 12, color: SHADE, align: 'center' });
}

// Draw one of the map tables. Regions are [color, x0,y0, x1,y1, ...] in map units.
function drawMap(s, map, o) {
  o = o || {};
  const k = map.span / map.unit;
  map.regions.forEach(function (region) {
    const fill = region[0];
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    for (let i = 1; i < region.length; i += 2) {
      minX = Math.min(minX, region[i]); maxX = Math.max(maxX, region[i]);
      minY = Math.min(minY, region[i + 1]); maxY = Math.max(maxY, region[i + 1]);
    }
    const pts = [];
    for (let i = 1; i < region.length; i += 2) {
      pts.push({ x: (region[i] - minX) * k, y: (region[i + 1] - minY) * k });
    }
    pts.push({ close: true });
    s.addShape('custGeom', {
      x: map.x + minX * k, y: map.y + minY * k,
      w: Math.max((maxX - minX) * k, 0.01), h: Math.max((maxY - minY) * k, 0.01),
      points: pts,
      fill: { color: fill, transparency: o.transparency },
      line: { color: o.stroke || INK, width: o.strokeWidth || 0.25, transparency: o.transparency },
    });
  });
}

